"""An automatic notification and the session's counters (owner's Q1, 2026-09-24; PLAN S11; task 173).

The chat-log hook reset the counters on EVERY prompt — also on a harness notification, which is not the user's prompt
and can land in the middle of a turn: measured on a live session on 2026-10-10, a background command's
`<task-notification>` took the counters from `tools=20 writes=20` to `0 0` between two tool calls of one turn (task
088's finding Q1). The owner's rule: "the stop hook's counters are no longer reset by an automatic notification".

Since task 340 the stop hook never blocks: it leaves a memento, and the chat-reply rule (writes 0, tools < 5) only
decides whether the memento shows. The rule's exception for a turn a notification started, and the two marks it rested
on (`turn_end`, `notif_start`, with the prompt generation `prompt_gen`), are gone with the block: there is nothing to
release. What stays here: a notification keeps the counts, a user's prompt resets them, a nested agent's prompt
resets nothing, an uncounted call is never read as a chat reply, and the batch guard across a notification.

These tests run the REAL hooks as subprocesses, in the order the events happen: `chat-log-hook` for a prompt,
`state-echo-hook` for a tool call, `stop-hook` for a stop.
"""

from __future__ import annotations

import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

from tests._bashcheck import bash_or_skip
from tests.test_batch_close_guard import G, NOTE, ProjectFixture, checked
from tests.test_batch_close_guard import SESSION as BATCH_SESSION

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = REPO_ROOT / "plugins" / "playbook" / "scripts"
SID = "pid-notif-turn"

NOTIFICATIONS = (
    "<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>",
    "[SYSTEM NOTIFICATION - NOT USER INPUT]\nThis is an automated background-task event.\n"
    "<task-notification>\n<task-id>b1</task-id>\n</task-notification>",
)
USER_COMMAND_ECHOES = (
    "<command-name>/playbook:work</command-name>\n<command-args>12</command-args>",
    "<local-command-caveat>Caveat: the messages below were generated by the user while "
    "running local commands.</local-command-caveat>",
)


class _Session(unittest.TestCase):
    """A project with one active task that has an open gate, and one session."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.project = Path(self._tmp.name) / "proj"
        task_dir = self.project / ".agent" / "tasks" / "001-x"
        task_dir.mkdir(parents=True)
        self.task_file = task_dir / "task.md"
        self.task_file.write_text(
            "# 001 - x\n\n## Status\nin_progress\n\n## Work Plan\n- [ ] a gate that is open\n",
            encoding="utf-8")
        self.session_dir = self.project / ".agent" / "sessions" / SID
        self.session_dir.mkdir(parents=True)
        (self.session_dir / "current_state").write_text("001\n", encoding="utf-8")
        self.counters_file = self.session_dir / "counters"
        # The stop hook asks the process chain whether the agent that stops is the
        # session's own. What a real chain holds depends on where the suite runs (CI:
        # no agent; a developer's session: one; a reviewer's sandbox: one or two), so
        # every hook here walks a fixture instead: a /proc with no agent in it.
        self.proc_root = Path(self._tmp.name) / "proc-no-agent"
        (self.proc_root / "self").mkdir(parents=True)

    def _nested_proc_root(self):
        """A /proc in which the process that starts the hooks (this test) is an agent
        whose PARENT is an agent too — the chain a nested `claude -p` leaves."""
        root = Path(self._tmp.name) / "proc-nested"
        (root / "self").mkdir(parents=True, exist_ok=True)
        for pid, parent in ((os.getpid(), 4242), (4242, 1)):
            d = root / str(pid)
            d.mkdir(exist_ok=True)
            (d / "status").write_text(f"Name:\tclaude\nState:\tS (sleeping)\nPPid:\t{parent}\n", encoding="utf-8")
            (d / "cmdline").write_bytes(b"claude\0-p\0do the thing\0")
        return root

    def _hook(self, name, payload, proc_root=None):
        env = dict(os.environ)
        env["PLAYBOOK_SESSION_ID"] = SID
        env["HOME"] = self._tmp.name
        env["PLAYBOOK_PROC_ROOT"] = str(proc_root or self.proc_root)
        for k in ("BASH_ENV", "PLAYBOOK_ROLE", "PLAYBOOK_EVAL_CONFIG"):
            env.pop(k, None)
        return subprocess.run(
            [bash_or_skip(), str(SCRIPTS / name)], cwd=self.project, env=env, text=True,
            input=json.dumps(payload), capture_output=True, timeout=60)

    # -- the events, as the harness sends them ---------------------------------------
    def prompt(self, text=None):
        if text is None:
            # each one different: the hook drops a message identical to the previous
            # one in the same second as a duplicate, before it resets anything
            self._n = getattr(self, "_n", 0) + 1
            text = f"a plain user prompt, number {self._n}"
        r = self._hook("chat-log-hook", {"prompt": text})
        self.assertEqual(r.returncode, 0, r.stderr)
        return r

    def tools(self, *names):
        for name in names:
            r = self._hook("state-echo-hook", {"tool_name": name, "tool_input": {"command": "true"}})
            self.assertEqual(r.returncode, 0, r.stderr)

    def stop(self, active=False, proc_root=None):
        return self._hook("stop-hook", {"stop_hook_active": active}, proc_root=proc_root)

    def counters(self) -> "dict[str, str]":
        if not self.counters_file.exists():
            return {}
        return dict(line.split("=", 1) for line in
                    self.counters_file.read_text(encoding="utf-8").splitlines() if "=" in line)

    def counts(self):
        c = self.counters()
        return int(c["tools"]), int(c["writes"])

    def memento(self, r) -> bool:
        """The stop ended (exit 0) and left its memento (task 340)."""
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        return "systemMessage" in r.stdout


class ANotificationDoesNotResetTheCounters(_Session):
    def test_an_automatic_notification_leaves_the_counts_as_they_were(self):
        for text in NOTIFICATIONS:
            with self.subTest(text[:24]):
                self.prompt()
                self.tools("Read", "Read", "Bash", "Read", "Bash")
                self.assertEqual(self.counts(), (5, 2))
                self.prompt(text)
                self.assertEqual(self.counts(), (5, 2),
                                 "a notification wiped the work count of the turn it landed in")

    def test_it_keeps_the_gate_fields_too(self):
        self.prompt()
        self.tools("Bash")
        with open(self.counters_file, "a", encoding="utf-8") as f:
            f.write("gate_x=1\n")
        self.prompt(NOTIFICATIONS[0])
        self.assertEqual(self.counters().get("gate_x"), "1")

    def test_the_echo_of_a_command_the_user_ran_still_resets(self):
        # `<command-name>` and `<local-command-caveat>` are skipped from the LOG like a
        # notification, but they are the user's act — a slash command, a `!` command —
        # and start a fresh count like any prompt of theirs.
        for text in USER_COMMAND_ECHOES:
            with self.subTest(text[:24]):
                self.prompt()
                self.tools("Read", "Bash", "Bash")
                self.prompt(text)
                self.assertEqual(self.counts(), (0, 0))

    def test_control_a_user_prompt_resets(self):
        self.prompt()
        self.tools("Read", "Bash", "Bash")
        self.prompt("and now something else")
        self.assertEqual(self.counts(), (0, 0))

    def test_with_no_counters_file_a_notification_creates_none(self):
        self.assertFalse(self.counters_file.exists())
        self.prompt(NOTIFICATIONS[0])
        self.assertFalse(self.counters_file.exists())


class ANestedAgentsPromptIsNotTheUsers(_Session):
    """Task 193 (PLAN S14 T4, #38), measured live on the candidate (evidence of task 193): a `claude -p` that the
    session's agent starts resolves to the SAME session, and its prompt's hook reset the outer turn's counts
    (`writes=2 tools=3` → 0) — a turn that had worked could then be released as a chat reply with gates open. The
    chat hook now applies the stop hook's rule: only the session's OWN agent (one agent in the hook's chain, or none
    visible) starts a new count; a nested agent's prompt resets nothing."""

    def _single_agent_proc_root(self):
        root = Path(self._tmp.name) / "proc-one-agent"
        (root / "self").mkdir(parents=True, exist_ok=True)
        d = root / str(os.getpid())
        d.mkdir(exist_ok=True)
        (d / "status").write_text("Name:\tclaude\nState:\tS (sleeping)\nPPid:\t1\n", encoding="utf-8")
        (d / "cmdline").write_bytes(b"claude\0")
        return root

    def nested_prompt(self, text="Reply with the single word OK."):
        r = self._hook("chat-log-hook", {"prompt": text}, proc_root=self._nested_proc_root())
        self.assertEqual(r.returncode, 0, r.stderr)

    def test_a_nested_agents_prompt_resets_nothing(self):
        self.prompt()
        self.tools("Bash", "Bash", "Read")           # the user's turn has worked
        self.nested_prompt()
        self.assertEqual(self.counts(), (3, 2), "a nested agent's prompt reset the session's turn")
        # said and journaled (impl panel r1, fable): a misread chain must leave a trace
        jf = self.project / ".agent" / "journal" / "enforcement.jsonl"
        rows = [json.loads(x) for x in jf.read_text(encoding="utf-8").splitlines() if x.strip()] if jf.exists() else []
        self.assertEqual([(x["hook"], x["decision"]) for x in rows if "nested" in x.get("reason", "")],
                         [("chat-log", "record")], rows)
        self.assertTrue(self.memento(self.stop()), "the user's turn was read as a chat reply")

    def test_control_the_sessions_own_prompt_resets(self):
        for root in (self.proc_root, self._single_agent_proc_root()):
            with self.subTest(chain=root.name):
                self.prompt()
                self.tools("Bash", "Bash", "Read")
                r = self._hook("chat-log-hook", {"prompt": f"the user again, {root.name}"}, proc_root=root)
                self.assertEqual(r.returncode, 0, r.stderr)
                self.assertEqual(self.counts(), (0, 0))


class AnUnsureCountThatCannotBeMarkedStillHoldsTheStop(_Session):
    """Task 193, impl panel r2 (opus, codex — codex ran it): `_counters_mark` refuses a sink that is a link, so with
    `counts_unsure` a dangling link and the counters lock not given, a tool call went uncounted AND unmarked, and the
    stop hook (which read only `-e`) took `writes=0` for a chat reply. Any `counts_unsure` entry — a dangling link
    included — or a linked session directory now keeps the chat-reply rule from applying (since task 340: the
    memento shows)."""

    def test_a_dangling_unsure_link_holds_the_stop(self):
        self.prompt()
        lock = self.session_dir / "counters.lock"
        lock.unlink(missing_ok=True)
        lock.mkdir()                                      # no plain file in the lock's place: not given
        (self.session_dir / "counts_unsure").unlink(missing_ok=True)
        (self.session_dir / "counts_unsure").symlink_to(Path(self._tmp.name) / "nowhere")
        self.tools("Bash")                                # uncounted, and the mark refused
        self.assertEqual(self.counts(), (0, 0))
        self.assertTrue(self.memento(self.stop()), "an uncounted write was read as a chat reply")


class TheConsecutiveBatchGuardAcrossANotification(unittest.TestCase):
    """The same reset had a second consequence. The gate-batch guard records the
    session's tool count when it allows a batch tick and blocks the next batch unless
    another tool call ran in between; a reset in between made the difference negative,
    so a notification between two batch ticks let the second one through."""

    def _notify(self, f):
        env = dict(os.environ, PLAYBOOK_SESSION_ID=BATCH_SESSION)
        for k in ("BASH_ENV", "PLAYBOOK_ROLE"):
            env.pop(k, None)
        r = subprocess.run([bash_or_skip(), str(SCRIPTS / "chat-log-hook")], cwd=f.proj, env=env,
                           text=True, input=json.dumps({"prompt": NOTIFICATIONS[0]}),
                           capture_output=True, timeout=60)
        self.assertEqual(r.returncode, 0, r.stderr)

    def test_a_notification_between_two_batch_ticks_does_not_free_the_second(self):
        f = ProjectFixture()
        f.set_tools_counter(10)
        r = f.run_hook(f.edit_payload(G[:2], [checked(g, NOTE) for g in G[:2]]))
        self.assertEqual(r.returncode, 0, r.stderr.decode())
        f.set_tools_counter(11)                      # the edit itself; nothing else ran
        self._notify(f)
        r = f.run_hook(f.edit_payload(G[2:4], [checked(g, NOTE) for g in G[2:4]]))
        self.assertEqual(r.returncode, 2, "the second batch went through:\n" + r.stderr.decode())


